SUPPORTED_LANGUAGES = ('en', 'uz', 'ru')


def t(lang: str, key: str, **kwargs) -> str:
    lang = lang if lang in TRANSLATIONS else 'en'
    text = TRANSLATIONS[lang].get(key, TRANSLATIONS['en'].get(key, key))
    return text.format(**kwargs) if kwargs else text


def prayer_name(lang: str, prayer_key: str) -> str:
    lang = lang if lang in PRAYER_NAMES else 'en'
    return PRAYER_NAMES[lang].get(prayer_key.lower(), prayer_key)


def detect_language(telegram_language_code: str | None) -> str:
    """Map a Telegram client language_code to one of our supported languages,
    defaulting to English for anything we don't recognize."""
    if not telegram_language_code:
        return 'en'
    code = telegram_language_code.lower()
    if code.startswith('uz'):
        return 'uz'
    if code.startswith('ru'):
        return 'ru'
    return 'en'


def format_prayer_times(lang: str, prayer_times: dict) -> str:
    lines = [t(lang, 'prayer_times_header')]
    for key in ('Fajr', 'Sunrise', 'Dhuhr', 'Asr', 'Maghrib', 'Isha'):
        lines.append(f"{prayer_name(lang, key)}:{prayer_times[key]}")
    return "\n".join(lines)
